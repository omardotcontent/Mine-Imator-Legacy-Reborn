	VarType vbuffer_create_cylinder(RealType rad, VecType tex1, VecType tex2, RealType thflip, RealType tvflip, VarType detail, VarType smooth, VarType closed, VarType invert, VarType mapped)
	{
		vbuffer_start();
		VecType texsize, texmid;
		texsize = point2D_sub(tex2, tex1);
		texmid = point2D_add(tex1, vec2_mul(texsize, 0.5));
		if (mapped > 0)
		{
			texsize = vec2((1.0 / 3.0) * thflip, tvflip);
			texmid.Real(Y_) = texsize.Real(Y_) / 2.0;
			tex1 = point2D(IntType(0), IntType(0));
			tex2 = point2D(abs(texsize.Real(X_)), abs(texsize.Real(Y_)));
			if (thflip < IntType(0))
			{
				RealType tmp = tex1.Real(X_);
				tex1.Real(X_) = tex2.Real(X_);
				tex2.Real(X_) = tmp;
			}
			if (tvflip < IntType(0))
			{
				RealType tmp = tex1.Real(Y_);
				tex1.Real(Y_) = tex2.Real(Y_);
				tex2.Real(Y_) = tmp;
			}
		}
		RealType i = IntType(0);
		for (IntType _it = 0, _it_max = detail; _it < _it_max; _it++)
		{
			RealType ip = i;
			i += 1.0 / detail;
			RealType n1x, n1y, n2x, n2y;
			RealType x1, y1, x2, y2;
			n1x = sin(ip * pi_ * IntType(2));
			n1y = cos(ip * pi_ * IntType(2));
			n2x = sin(i * pi_ * IntType(2));
			n2y = cos(i * pi_ * IntType(2));
			x1 = n1x * rad;
			y1 = n1y * rad;
			x2 = n2x * rad;
			y2 = n2y * rad;
			if (invert > 0)
			{
				n1x *= -1.0;
				n1y *= -1.0;
				n2x *= -1.0;
				n2y *= -1.0;
			}
			if (closed > 0)
			{
				if (mapped > 0)
					texmid.Real(X_) = 5.0 / 6.0;
				vbuffer_add_triangle({ IntType(0), IntType(0), -rad, x1, y1, -rad, x2, y2, -rad, texmid.Real(X_), texmid.Real(Y_), texmid.Real(X_) + sin(ip * pi_ * IntType(2)) * (texsize.Real(X_) / 2.0), texmid.Real(Y_) - cos(ip * pi_ * IntType(2)) * (texsize.Real(Y_) / 2.0), texmid.Real(X_) + sin(i * pi_ * IntType(2)) * (texsize.Real(X_) / 2.0), texmid.Real(Y_) - cos(i * pi_ * IntType(2)) * (texsize.Real(Y_) / 2.0), invert });
				if (mapped > 0)
					texmid.Real(X_) = 0.5;
				vbuffer_add_triangle({ IntType(0), IntType(0), rad, x2, y2, rad, x1, y1, rad, texmid.Real(X_), texmid.Real(Y_), texmid.Real(X_) + sin(i * pi_ * IntType(2)) * (texsize.Real(X_) / 2.0), texmid.Real(Y_) + cos(i * pi_ * IntType(2)) * (texsize.Real(Y_) / 2.0), texmid.Real(X_) + sin(ip * pi_ * IntType(2)) * (texsize.Real(X_) / 2.0), texmid.Real(Y_) + cos(ip * pi_ * IntType(2)) * (texsize.Real(Y_) / 2.0), invert });
			}
			if (!(smooth > 0))
			{
				RealType normx, normy;
				normx = (n1x + n2x) / 2.0;
				normy = (n1y + n2y) / 2.0;
				n1x = normx;
				n2x = normx;
				n1y = normy;
				n2y = normy;
			}
			if (invert > 0)
			{
				vertex_add({ x1, y1, rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) });
				vertex_add({ x1, y1, -rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) + texsize.Real(Y_) });
				vertex_add({ x2, y2, rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) });
				vertex_add({ x2, y2, -rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) + texsize.Real(Y_) });
				vertex_add({ x2, y2, rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) });
				vertex_add({ x1, y1, -rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) + texsize.Real(Y_) });
			}
			else
			{
				vertex_add({ x1, y1, -rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) + texsize.Real(Y_) });
				vertex_add({ x1, y1, rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) });
				vertex_add({ x2, y2, rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) });
				vertex_add({ x2, y2, rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) });
				vertex_add({ x2, y2, -rad, n2x, n2y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * i, tex1.Real(Y_) + texsize.Real(Y_) });
				vertex_add({ x1, y1, -rad, n1x, n1y, IntType(0), tex1.Real(X_) + texsize.Real(X_) * ip, tex1.Real(Y_) + texsize.Real(Y_) });
			}
			
		}
		return vbuffer_done();
	}
	
	VarType vbuffer_create_path(Scope<obj_timeline> self, IntType path, BoolType small_)
	{
		ArrType points;
		VarType closed, detail, radius, invert, mapped, fixlength, texlength;
		BoolType rail;
		VecType texoffset, texrepeat, texmirror;
		points = ObjType(obj_timeline, path)->path_table;
		closed = ObjType(obj_timeline, path)->path_closed;
		detail = ObjType(obj_timeline, path)->path_shape_detail;
		rail = ObjType(obj_timeline, path)->path_shape == /*"flat"*/ STR(843);
		radius = ObjType(obj_timeline, path)->path_shape_radius;
		invert = ObjType(obj_timeline, path)->path_shape_invert;
		mapped = ObjType(obj_timeline, path)->path_shape_tex_mapped;
		fixlength = ObjType(obj_timeline, path)->path_shape_tex_fixed;
		texoffset = vec2(ObjType(obj_timeline, path)->path_shape_tex_hoffset, ObjType(obj_timeline, path)->path_shape_tex_voffset);
		texrepeat = vec2(ObjType(obj_timeline, path)->path_shape_tex_hrepeat, ObjType(obj_timeline, path)->path_shape_tex_vrepeat);
		texmirror = vec2(ObjType(obj_timeline, path)->path_shape_tex_hmirror, ObjType(obj_timeline, path)->path_shape_tex_vmirror);
		texlength = ObjType(obj_timeline, path)->path_shape_tex_length;
		if (small_)
		{
			radius = IntType(1);
			detail = IntType(4);
			rail = false;
			invert = false;
		}
		vbuffer_start();
		ArrType frames;
		VarType p;
		for (IntType i = IntType(0); i < array_length(VarType::CreateRef(points)); i++)
		{
			p = points.Value(i);
			frames[i] = matrix_create_rotate_to(ArrType::From({ p.Value(PATH_TANGENT_X), p.Value(PATH_TANGENT_Y), p.Value(PATH_TANGENT_Z) }), ArrType::From({ p.Value(PATH_NORMAL_X), p.Value(PATH_NORMAL_Y), p.Value(PATH_NORMAL_Z) }));
		}
		VecType p1, p2, p3, p4;
		VecType n1, n2, n3, n4, nflatp, nflat;
		VecType nn1, nn2, nn3, nn4;
		VecType t1, t2, t3, t4;
		RealType jp, j;
		ArrType ringp;
		RealType length, prevlength, totallength;
		length = IntType(0);
		prevlength = IntType(0);
		totallength = IntType(0);
		if (!(fixlength > 0))
			for (IntType i = IntType(0); i < array_length(VarType::CreateRef(frames)) - IntType(1); i++)
				totallength += point3D_distance(points.Value(i), points.Value(i + IntType(1)));
		for (IntType i = IntType(0); i < array_length(VarType::CreateRef(frames)) - IntType(1); i++)
		{
			if (!rail)
			{
				jp = IntType(0);
				j = 1.0 / detail;
				ringp = ArrType::From({ sin(jp * pi_ * IntType(2)), IntType(0), cos(jp * pi_ * IntType(2)) });
			}
			else
			{
				jp = .5;
				ringp = ArrType::From({ cos(jp * pi_ * IntType(2)), IntType(0), -sin(jp * pi_ * IntType(2)) });
			}
			
			prevlength = length;
			length += point3D_distance(points.Value(i), points.Value(i + IntType(1)));
			if (!(fixlength > 0))
				texlength = totallength;
			n1 = vec3_normalize(vec3_mul_matrix(ringp, frames.Value(i)));
			p1 = point3D_add(vec3_mul(n1, radius * points[i][IntType(4)]), points.Value(i));
			n3 = vec3_normalize(vec3_mul_matrix(ringp, frames.Value(i + IntType(1))));
			p3 = point3D_add(vec3_mul(n3, radius * points[i + IntType(1)][IntType(4)]), points.Value(i + IntType(1)));
			jp = IntType(0);
			j = IntType(0);
			while (j < IntType(1))
			{
				if (!rail)
				{
					jp = j;
					j += 1.0 / detail;
					ringp = ArrType::From({ sin(j * pi_ * IntType(2)), IntType(0), cos(j * pi_ * IntType(2)) });
				}
				else
				{
					j = IntType(0);
					ringp = ArrType::From({ cos(j * pi_ * IntType(2)), IntType(0), -sin(j * pi_ * IntType(2)) });
				}
				
				n2 = vec3_normalize(vec3_mul_matrix(ringp, frames.Value(i)));
				p2 = point3D_add(vec3_mul(n2, radius * points[i][IntType(4)]), points.Value(i));
				n4 = vec3_normalize(vec3_mul_matrix(ringp, frames.Value(i + IntType(1))));
				p4 = point3D_add(vec3_mul(n4, radius * points[i + IntType(1)][IntType(4)]), points.Value(i + IntType(1)));
				if (rail)
				{
					t1 = vec2(IntType(0), prevlength / texlength);
					t2 = vec2(IntType(1), prevlength / texlength);
					t3 = vec2(IntType(0), length / texlength);
					t4 = vec2(IntType(1), length / texlength);
					n1 = ArrType::From({ frames[i][IntType(8)], frames[i][IntType(9)], frames[i][IntType(10)] });
					n2 = n1;
					n3 = ArrType::From({ frames[i + IntType(1)][IntType(8)], frames[i + IntType(1)][IntType(9)], frames[i + IntType(1)][IntType(10)] });
					n4 = n3;
				}
				else
				{
					t1 = vec2(jp, prevlength / texlength);
					t2 = vec2(j, prevlength / texlength);
					t3 = vec2(jp, length / texlength);
					t4 = vec2(j, length / texlength);
				}
				
				if (mapped > 0)
				{
					t1.Real(X_) /= 3.0;
					t2.Real(X_) /= 3.0;
					t3.Real(X_) /= 3.0;
					t4.Real(X_) /= 3.0;
				}
				if (texmirror.Real(Y_))
				{
					t1.Real(Y_) = 1.0 - t1.Real(Y_);
					t2.Real(Y_) = 1.0 - t2.Real(Y_);
					t3.Real(Y_) = 1.0 - t3.Real(Y_);
					t4.Real(Y_) = 1.0 - t4.Real(Y_);
				}
				if (texmirror.Real(X_))
				{
					t1.Real(X_) = 1.0 - t1.Real(X_);
					t2.Real(X_) = 1.0 - t2.Real(X_);
					t3.Real(X_) = 1.0 - t3.Real(X_);
					t4.Real(X_) = 1.0 - t4.Real(X_);
				}
				if (!(mapped > 0))
				{
					t1.Real(X_) += texoffset.Real(X_);
					t1.Real(Y_) += texoffset.Real(Y_);
					t2.Real(X_) += texoffset.Real(X_);
					t2.Real(Y_) += texoffset.Real(Y_);
					t3.Real(X_) += texoffset.Real(X_);
					t3.Real(Y_) += texoffset.Real(Y_);
					t4.Real(X_) += texoffset.Real(X_);
					t4.Real(Y_) += texoffset.Real(Y_);
					t1.Real(X_) *= texrepeat.Real(X_);
					t2.Real(X_) *= texrepeat.Real(X_);
					t3.Real(X_) *= texrepeat.Real(X_);
					t4.Real(X_) *= texrepeat.Real(X_);
					if (!(fixlength > 0))
					{
						t1.Real(Y_) *= texrepeat.Real(Y_);
						t2.Real(Y_) *= texrepeat.Real(Y_);
						t3.Real(Y_) *= texrepeat.Real(Y_);
						t4.Real(Y_) *= texrepeat.Real(Y_);
					}
				}
				else
					if (texmirror.Real(X_))
					{
						t1.Real(X_) -= 2.0 / 3.0;
						t2.Real(X_) -= 2.0 / 3.0;
						t3.Real(X_) -= 2.0 / 3.0;
						t4.Real(X_) -= 2.0 / 3.0;
					}
				
				nn1 = n1;
				nn2 = n2;
				nn3 = n3;
				nn4 = n4;
				if (invert > 0)
				{
					nn1 = vec3_mul(nn1, -IntType(1));
					nn2 = vec3_mul(nn2, -IntType(1));
					nn3 = vec3_mul(nn3, -IntType(1));
					nn4 = vec3_mul(nn4, -IntType(1));
				}
				if (ObjType(obj_timeline, path)->path_shape_smooth_segments > 0 && !(ObjType(obj_timeline, path)->path_shape_smooth_ring > 0))
				{
					nflatp = vec3_normalize(vec3_add(nn1, nn2));
					nflat = vec3_normalize(vec3_add(nn3, nn4));
					nn1 = nflatp;
					nn2 = nflatp;
					nn3 = nflat;
					nn4 = nflat;
				}
				else
					if (!(ObjType(obj_timeline, path)->path_shape_smooth_segments > 0) && ObjType(obj_timeline, path)->path_shape_smooth_ring > 0)
					{
						nflatp = vec3_normalize(vec3_add(nn1, nn3));
						nflat = vec3_normalize(vec3_add(nn2, nn4));
						nn1 = nflatp;
						nn2 = nflat;
						nn3 = nflatp;
						nn4 = nflat;
					}
					else
						if (!(self->path_shape_smooth_segments > 0) && !(self->path_shape_smooth_ring > 0))
						{
							nflat = vec3_normalize(vec3_add(vec3_add(vec3_add(nn1, nn2), nn3), nn4));
							nn1 = nflat;
							nn2 = nflat;
							nn3 = nflat;
							nn4 = nflat;
						}
				
				
				if (invert > 0)
				{
					vbuffer_add_triangle({ p2, p1, p4, t2, t1, t4, nn2, nn1, nn4 });
					vbuffer_add_triangle({ p1, p3, p4, t1, t3, t4, nn1, nn3, nn4 });
				}
				else
				{
					vbuffer_add_triangle({ p4, p1, p2, t4, t1, t2, nn4, nn1, nn2 });
					vbuffer_add_triangle({ p4, p3, p1, t4, t3, t1, nn4, nn3, nn1 });
				}
				
				if (rail)
					break;
				if (!(closed > 0))
				{
					t1 = ArrType::From({ (cos((jp + .25) * pi_ * IntType(2)) + 1.0) / 2.0, (sin((jp + .25) * pi_ * IntType(2)) + 1.0) / 2.0 });
					t2 = ArrType::From({ (cos((j + .25) * pi_ * IntType(2)) + 1.0) / 2.0, (sin((j + .25) * pi_ * IntType(2)) + 1.0) / 2.0 });
					t3 = ArrType::From({ .5, .5 });
					if (mapped > 0)
					{
						t1.Real(X_) = (t1.Real(X_) / 3.0) + (1.0 / 3.0);
						t2.Real(X_) = (t2.Real(X_) / 3.0) + (1.0 / 3.0);
						t3.Real(X_) = (t3.Real(X_) / 3.0) + (1.0 / 3.0);
					}
					else
					{
						t1.Real(X_) += texoffset.Real(X_);
						t1.Real(Y_) += texoffset.Real(Y_);
						t2.Real(X_) += texoffset.Real(X_);
						t2.Real(Y_) += texoffset.Real(Y_);
						t3.Real(X_) += texoffset.Real(X_);
						t3.Real(Y_) += texoffset.Real(Y_);
						t1.Real(X_) -= texoffset.Real(X_) * IntType(2);
						t2.Real(X_) -= texoffset.Real(X_) * IntType(2);
						t3.Real(X_) -= texoffset.Real(X_) * IntType(2);
						t1.Real(X_) *= texrepeat.Real(X_);
						t2.Real(X_) *= texrepeat.Real(X_);
						t3.Real(X_) *= texrepeat.Real(X_);
						t1.Real(Y_) *= texrepeat.Real(Y_);
						t2.Real(Y_) *= texrepeat.Real(Y_);
						t3.Real(Y_) *= texrepeat.Real(Y_);
					}
					
					t1.Real(X_) = 1.0 - t1.Real(X_);
					t2.Real(X_) = 1.0 - t2.Real(X_);
					t3.Real(X_) = 1.0 - t3.Real(X_);
					if (texmirror.Real(X_))
					{
						t1.Real(X_) = 1.0 - t1.Real(X_);
						t2.Real(X_) = 1.0 - t2.Real(X_);
						t3.Real(X_) = 1.0 - t3.Real(X_);
					}
					if (texmirror.Real(Y_))
					{
						t1.Real(Y_) = 1.0 - t1.Real(Y_);
						t2.Real(Y_) = 1.0 - t2.Real(Y_);
						t3.Real(Y_) = 1.0 - t3.Real(Y_);
					}
					if (i == IntType(0))
					{
						if (invert > 0)
							vbuffer_add_triangle({ p2, points.Value(i), p1, t2, t3, t1 });
						else
							vbuffer_add_triangle({ p1, points.Value(i), p2, t1, t3, t2 });
						
					}
					if (i == (array_length(VarType::CreateRef(points)) - IntType(2)))
					{
						if (mapped > 0)
						{
							t1.Real(X_) += (1.0 / 3.0);
							t2.Real(X_) += (1.0 / 3.0);
							t3.Real(X_) += (1.0 / 3.0);
						}
						else
						{
							t1.Real(Y_) -= texoffset.Real(Y_) * IntType(2);
							t2.Real(Y_) -= texoffset.Real(Y_) * IntType(2);
							t3.Real(Y_) -= texoffset.Real(Y_) * IntType(2);
						}
						
						t1.Real(Y_) = 1.0 - t1.Real(Y_);
						t2.Real(Y_) = 1.0 - t2.Real(Y_);
						t3.Real(Y_) = 1.0 - t3.Real(Y_);
						if (invert > 0)
							vbuffer_add_triangle({ p3, points.Value(i + IntType(1)), p4, t1, t3, t2 });
						else
							vbuffer_add_triangle({ p4, points.Value(i + IntType(1)), p3, t2, t3, t1 });
						
					}
				}
				p1 = p2;
				p3 = p4;
				n1 = n2;
				n3 = n4;
			}
			
		}
		return vbuffer_done();
	}
	
	VarType vbuffer_create_sphere(RealType rad, VecType tex1, VecType tex2, VarType detail, VarType ringdetail, VarType smooth, VarType invert)
	{
		vbuffer_start();
		VecType texsize;
		RealType n;
		texsize = point2D_sub(tex2, tex1);
		n = negate(invert);
		RealType i = IntType(0);
		for (IntType _it = 0, _it_max = detail; _it < _it_max; _it++)
		{
			RealType j, ip, ipi2, ippi2;
			ip = i;
			i += 1.0 / detail;
			ippi2 = ip * pi_ * IntType(2);
			ipi2 = i * pi_ * IntType(2);
			j = IntType(0);
			for (IntType _it = 0, _it_max = ringdetail; _it < _it_max; _it++)
			{
				RealType jp, jpi, jppi;
				jp = j;
				j += 1.0 / ringdetail;
				jppi = jp * pi_;
				jpi = j * pi_;
				RealType x1, y1, z1, x2, y2, z2, x3, y3, z3, x4, y4, z4;
				x1 = (rad * sin(jpi)) * sin(ipi2);
				y1 = (rad * sin(jpi)) * cos(ipi2);
				z1 = rad * cos(jpi);
				x2 = (rad * sin(jppi)) * sin(ipi2);
				y2 = (rad * sin(jppi)) * cos(ipi2);
				z2 = rad * cos(jppi);
				x3 = (rad * sin(jpi)) * sin(ippi2);
				y3 = (rad * sin(jpi)) * cos(ippi2);
				z3 = rad * cos(jpi);
				x4 = (rad * sin(jppi)) * sin(ippi2);
				y4 = (rad * sin(jppi)) * cos(ippi2);
				z4 = rad * cos(jppi);
				RealType n1x, n1y, n1z, n2x, n2y, n2z, n3x, n3y, n3z, n4x, n4y, n4z;
				n1x = sin(jpi) * sin(ipi2);
				n1y = sin(jpi) * cos(ipi2);
				n1z = cos(jpi);
				n2x = sin(jppi) * sin(ipi2);
				n2y = sin(jppi) * cos(ipi2);
				n2z = cos(jppi);
				n3x = sin(jpi) * sin(ippi2);
				n3y = sin(jpi) * cos(ippi2);
				n3z = cos(jpi);
				n4x = sin(jppi) * sin(ippi2);
				n4y = sin(jppi) * cos(ippi2);
				n4z = cos(jppi);
				if (!(smooth > 0))
				{
					RealType normx, normy, normz;
					normx = (n1x + n2x + n3x + n4x) / 4.0;
					normy = (n1y + n2y + n3y + n4y) / 4.0;
					normz = (n1z + n2z + n3z + n4z) / 4.0;
					n1x = normx;
					n2x = normx;
					n3x = normx;
					n4x = normx;
					n1y = normy;
					n2y = normy;
					n3y = normy;
					n4y = normy;
					n1z = normz;
					n2z = normz;
					n3z = normz;
					n4z = normz;
				}
				RealType u1, u2, v1, v2;
				u1 = tex1.Real(X_) + ip * texsize.Real(X_);
				u2 = tex1.Real(X_) + i * texsize.Real(X_);
				v1 = tex1.Real(Y_) + jp * texsize.Real(Y_);
				v2 = tex1.Real(Y_) + j * texsize.Real(Y_);
				if (invert > 0)
				{
					vertex_add({ x3, y3, z3, n3x * n, n3y * n, n3z * n, u1, v2 });
					vertex_add({ x1, y1, z1, n1x * n, n1y * n, n1z * n, u2, v2 });
					vertex_add({ x2, y2, z2, n2x * n, n2y * n, n2z * n, u2, v1 });
					vertex_add({ x3, y3, z3, n3x * n, n3y * n, n3z * n, u1, v2 });
					vertex_add({ x2, y2, z2, n2x * n, n2y * n, n2z * n, u2, v1 });
					vertex_add({ x4, y4, z4, n4x * n, n4y * n, n4z * n, u1, v1 });
				}
				else
				{
					vertex_add({ x1, y1, z1, n1x * n, n1y * n, n1z * n, u2, v2 });
					vertex_add({ x3, y3, z3, n3x * n, n3y * n, n3z * n, u1, v2 });
					vertex_add({ x2, y2, z2, n2x * n, n2y * n, n2z * n, u2, v1 });
					vertex_add({ x2, y2, z2, n2x * n, n2y * n, n2z * n, u2, v1 });
					vertex_add({ x3, y3, z3, n3x * n, n3y * n, n3z * n, u1, v2 });
					vertex_add({ x4, y4, z4, n4x * n, n4y * n, n4z * n, u1, v1 });
				}
				
			}
		}
		return vbuffer_done();
	}
	
	VarType vbuffer_create_surface(RealType rad, VecType tex1, VecType tex2, VarType invert)
	{
		vbuffer_start();
		vbuffer_add_triangle({ -rad, IntType(0), rad, rad, IntType(0), rad, rad, IntType(0), -rad, tex1.Real(X_), tex1.Real(Y_), tex2.Real(X_), tex1.Real(Y_), tex2.Real(X_), tex2.Real(Y_), invert });
		vbuffer_add_triangle({ -rad, IntType(0), -rad, -rad, IntType(0), rad, rad, IntType(0), -rad, tex1.Real(X_), tex2.Real(Y_), tex1.Real(X_), tex1.Real(Y_), tex2.Real(X_), tex2.Real(Y_), invert });
		return vbuffer_done();
	}
	
	void vbuffer_destroy(VarType vbuf)
	{
		vertex_delete_buffer((IntType)(vbuf));
	}
	

			json_save_var(/*"author"*/ STR(2518), json_string_encode(idVar(recent, author)));
			json_save_var(/*"description"*/ STR(1966), json_string_encode(idVar(recent, description)));
			json_save_var(/*"thumbnail"*/ STR(2843), idVar(recent, thumbnail));

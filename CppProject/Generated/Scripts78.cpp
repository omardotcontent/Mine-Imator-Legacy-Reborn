	void tl_ext_history_save_tl(IntType tlId, IntType saveId)
	{
		g_extSavedTlKfs.remove(saveId);
		if (!instance_exists(tlId))
			return;
		obj_timeline* tlObj = ObjType(obj_timeline, tlId);
		if (!tlObj || !ds_list_valid(tlObj->keyframe_list))
			return;
		QHash<RealType, TlExtData> kfs;
		for (IntType k = 0; k < ds_list_size(tlObj->keyframe_list); k++)
		{
			IntType kfId = (IntType)DsList(tlObj->keyframe_list).Value(k);
			if (g_kfExtMap.contains(kfId))
				kfs[(RealType)ObjType(obj_keyframe, kfId)->position] = g_kfExtMap[kfId];
		}
		if (!kfs.isEmpty())
			g_extSavedTlKfs[saveId] = kfs;
	}


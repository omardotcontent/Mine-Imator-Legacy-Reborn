	extern RealType g_render_point_shadow_cache_hash;

	void tl_ext_append_hdr_emissive_lights(ScopeAny self, VarType resultsurf)
	{
		if (!surface_exists((IntType)resultsurf))
			return;

		struct ShadowedHdrEmitter
		{
			IntType tlId;
			IntType color;
			RealType strength;
			RealType range;
			RealType fadeSize;
			QVector<VecType> pts;
		};
		QVector<ShadowedHdrEmitter> shadowedList;
		IntType hdrShadowlessCount = 0;

		withAll (obj_timeline, noone)
		{
			if (!HasTlExt(self->id))
				continue;
			const TlExtData& ext = GetTlExt(self->id);
			if (!ext.hdr_light_enable || !self->render_visible || self->hide > 0 || ext.hdr_light_strength <= 0.001)
				continue;
			obj_timeline* tlObj = ObjType(obj_timeline, self->id);

			IntType col = ResolveHdrLightColor(ext, tlObj);
			QVector<VecType> samplePts;
			CollectHdrLightSamplePoints(tlObj, samplePts);
			if (samplePts.isEmpty())
				continue;

			if (ext.hdr_light_shadows)
			{
				ShadowedHdrEmitter em;
				em.tlId = tlObj->id;
				em.color = col;
				em.strength = ext.hdr_light_strength;
				em.range = ext.hdr_light_range;
				em.fadeSize = ext.hdr_light_fade_size;
				if (samplePts.size() == 1)
				{
					em.pts.append(samplePts[0]);
				}
				else
				{
					// Use up to 2 representative points for multi-part/elongated shapes so shadows stay crisp & fast
					VecType firstP = samplePts.first();
					VecType lastP = samplePts.last();
					if (point3D_distance(firstP, lastP) > 18.0)
					{
						em.pts.append(firstP);
						em.pts.append(lastP);
					}
					else
					{
						em.pts.append(AverageSamplePoints(samplePts, firstP));
					}
				}
				shadowedList.append(em);
			}
			else
			{
				// Fast shadowless multi-sample area light batch
				RealType perSampleStr = ext.hdr_light_strength / std::pow((double)samplePts.size(), 0.78);
				RealType r = ((RealType)color_get_red(col) / 255.0) * perSampleStr;
				RealType g = ((RealType)color_get_green(col) / 255.0) * perSampleStr;
				RealType b = ((RealType)color_get_blue(col) / 255.0) * perSampleStr;

				for (VecType pt : samplePts)
				{
					if (hdrShadowlessCount >= 32)
						break;
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 0] = pt.Real(X_);
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 1] = pt.Real(Y_);
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 2] = pt.Real(Z_);
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 3] = ext.hdr_light_range;
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 4] = r;
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 5] = g;
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 6] = b;
					global::render_shadowless_point_data[hdrShadowlessCount * 8 + 7] = ext.hdr_light_fade_size;
					hdrShadowlessCount++;
				}
			}
		}

		// 1. Render real 6-face cubemap shadows for shadow-casting Emit Light objects (excluding emitter itself!)
		if (!shadowedList.isEmpty())
		{
			IntType prevLightAmt = global::render_light_amount;
			if (global::render_light_amount < IntType(1))
				global::render_light_amount = IntType(1);
			g_render_point_shadow_cache_hash = -1.0;

			for (const ShadowedHdrEmitter& em : shadowedList)
			{
				RealType perPtStr = em.strength / std::pow((double)em.pts.size(), 0.78);
				for (VecType lpos : em.pts)
				{
					g_hdr_shadow_exclude_tl = em.tlId;
					for (IntType d = e_dir_EAST; d < e_dir_amount; d++)
					{
						VecType look = dir_get_vec3(d);
						if (d == e_dir_DOWN || d == e_dir_UP)
							look.Real(Y_) -= 0.0001;
						global::render_surface_point_buffer[d] = surface_require(global::render_surface_point_buffer.Value(d), global::_app->project_render_shadows_point_buffer_size, global::_app->project_render_shadows_point_buffer_size);
						surface_set_target((IntType)(global::render_surface_point_buffer.Value(d)));
						{
							gpu_set_blendmode_ext(bm_one, bm_zero);
							draw_clear(c_white);
							render_world_start_light(lpos, point3D_add(lpos, look), IntType(1), em.range, IntType(90), em.color, em.fadeSize, IntType(0), perPtStr);
							render_world(self, e_render_mode_HIGH_LIGHT_POINT_DEPTH);
							render_world_done();
							gpu_set_blendmode(bm_normal);
						}
						surface_reset_target();
					}
					g_hdr_shadow_exclude_tl = null_;

					global::render_surface[IntType(2)] = surface_require(global::render_surface.Value(IntType(2)), global::render_width, global::render_height);
					VarType resultsurftemp = global::render_surface.Value(IntType(2));
					surface_set_target((IntType)resultsurftemp);
					{
						draw_clear(c_black);
						render_world_start();
						render_world(self, e_render_mode_HIGH_LIGHT_POINT);
						render_world_done();
					}
					surface_reset_target();

					surface_set_target((IntType)resultsurf);
					{
						gpu_set_blendmode(bm_add);
						draw_surface_exists(resultsurftemp, IntType(0), IntType(0));
						gpu_set_blendmode(bm_normal);
					}
					surface_reset_target();
				}
			}
			global::render_light_amount = prevLightAmt;
		}

		// 2. Render shadowless Emit Lights batch
		if (hdrShadowlessCount > 0)
		{
			global::render_shadowless_point_amount = hdrShadowlessCount;
			global::render_surface[IntType(2)] = surface_require(global::render_surface.Value(IntType(2)), global::render_width, global::render_height);
			VarType resultsurftemp = global::render_surface.Value(IntType(2));
			surface_set_target((IntType)resultsurftemp);
			{
				draw_clear(c_black);
				render_world_start();
				render_world(self, e_render_mode_HIGH_LIGHT_POINT_SHADOWLESS);
				render_world_done();
			}
			surface_reset_target();

			surface_set_target((IntType)resultsurf);
			{
				gpu_set_blendmode(bm_add);
				draw_surface_exists(resultsurftemp, IntType(0), IntType(0));
				gpu_set_blendmode(bm_normal);
			}
			surface_reset_target();
		}
	}

	BoolType tl_ext_should_skip_render(IntType tlId)
	{
		// Exclude the currently shadow-casting Emit Light object (and its child parts) from its own shadow cubemap
		if (g_hdr_shadow_exclude_tl != null_ && global::render_mode == e_render_mode_HIGH_LIGHT_POINT_DEPTH)
		{
			if (tlId == g_hdr_shadow_exclude_tl)
				return true;
			if (instance_exists(tlId) && (IntType)ObjType(obj_timeline, tlId)->part_of == g_hdr_shadow_exclude_tl)
				return true;
		}
		if (!HasTlExt(tlId))
			return false;
		const TlExtData& ext = GetTlExt(tlId);
		if (g_rendering_planar_mirror && tlId == g_active_mirror_tl)
			return true;
		if (ext.volume_mode > 0 && global::render_mode != e_render_mode_CLICK && global::render_mode != e_render_mode_SELECT && global::render_mode != e_render_mode_PLACE)
			return true;
		return false;
	}

	void tl_ext_setup_mirror_pass_uniforms()
	{
		Shader* sh = GFX ? GFX->shader : nullptr;
		if (!sh)
			return;
		IntType uIsMirror = sh->GetUniformIndex(StringType("uIsPlanarMirror"));
		if (uIsMirror >= 0)
			sh->SubmitInt(uIsMirror, 0);
		IntType uClip = sh->GetUniformIndex(StringType("uMirrorClipPlane"));
		if (uClip >= 0)
		{
			if (g_rendering_planar_mirror)
				sh->SubmitVec4(uClip, g_planar_mirror_clip_plane.Real(0), g_planar_mirror_clip_plane.Real(1), g_planar_mirror_clip_plane.Real(2), g_planar_mirror_clip_plane.Real(3));
			else
				sh->SubmitVec4(uClip, 0.0, 0.0, 0.0, 0.0);
		}
	}

	void tl_ext_setup_render_uniforms(IntType tlId)
	{
		Shader* sh = GFX ? GFX->shader : nullptr;
		if (!sh)
			return;

		IntType uIsMirror = sh->GetUniformIndex(StringType("uIsPlanarMirror"));

		if (g_rendering_planar_mirror)
		{
			if (uIsMirror >= 0)
				sh->SubmitInt(uIsMirror, 0);
			return;
		}

		if (HasTlExt(tlId))
		{
			const TlExtData& ext = GetTlExt(tlId);
			VarType msurf = g_planar_mirror_surfs.value(tlId, null_);
			if (ext.mirror_enable && msurf != null_ && surface_exists((IntType)msurf) && g_planar_mirror_vps.contains(tlId))
			{
				if (uIsMirror >= 0)
				{
					GFX->SubmitBatch();
					sh->SubmitInt(uIsMirror, 1);
					IntType uStr = sh->GetUniformIndex(StringType("uMirrorStrength"));
					if (uStr >= 0)
						sh->SubmitFloat(uStr, ext.mirror_strength);
					MatrixType mvp = g_planar_mirror_vps[tlId];
					IntType uVPX = sh->GetUniformIndex(StringType("uMirrorVPX"));
					IntType uVPY = sh->GetUniformIndex(StringType("uMirrorVPY"));
					IntType uVPW = sh->GetUniformIndex(StringType("uMirrorVPW"));
					if (uVPX >= 0)
						sh->SubmitVec4(uVPX, mvp.Real(0), mvp.Real(4), mvp.Real(8), mvp.Real(12));
					if (uVPY >= 0)
						sh->SubmitVec4(uVPY, mvp.Real(1), mvp.Real(5), mvp.Real(9), mvp.Real(13));
					if (uVPW >= 0)
						sh->SubmitVec4(uVPW, mvp.Real(3), mvp.Real(7), mvp.Real(11), mvp.Real(15));
					IntType sMirror = sh->GetSamplerIndex(StringType("uMirrorTexture"));
					if (sMirror >= 0)
					{
						texture_set_stage(sMirror, surface_get_texture((IntType)msurf));
						gpu_set_texfilter_ext(sMirror, true);
						gpu_set_texrepeat_ext(sMirror, false);
					}
				}
				render_set_uniform(/*"uBrightness"*/ STR(2872), std::max((double)global::shader_uniform_emissive, (double)ext.mirror_strength));
				global::shader_uniform_emissive = -IntType(1);
			}
			else if (uIsMirror >= 0)
				sh->SubmitInt(uIsMirror, 0);

			if (ext.hdr_light_enable)
			{
				render_set_uniform(/*"uBrightness"*/ STR(2872), std::max((double)global::shader_uniform_emissive, std::min(1.0, (double)ext.hdr_light_strength * 0.65)));
				global::shader_uniform_emissive = -IntType(1);
				if (global::render_mode == e_render_mode_COLOR_GLOW)
				{
					IntType gcol = ResolveHdrLightColor(ext, ObjType(obj_timeline, tlId));
					render_set_uniform_int(/*"uGlow"*/ STR(2878), IntType(1));
					render_set_uniform_color(/*"uGlowColor"*/ STR(2866), gcol, IntType(1));
					global::shader_uniform_glow = -IntType(1);
				}
			}
		}
		else
		{
			if (uIsMirror >= 0)
				sh->SubmitInt(uIsMirror, 0);
			// Propagate parent Character / Model HDR Emit light glow & brightness to its child body parts!
			obj_timeline* tlObj = ObjType(obj_timeline, tlId);
			if (tlObj && tlObj->part_of != null_ && HasTlExt((IntType)tlObj->part_of))
			{
				const TlExtData& pext = GetTlExt((IntType)tlObj->part_of);
				if (pext.hdr_light_enable)
				{
					render_set_uniform(/*"uBrightness"*/ STR(2872), std::max((double)global::shader_uniform_emissive, std::min(1.0, (double)pext.hdr_light_strength * 0.65)));
					global::shader_uniform_emissive = -IntType(1);
					if (global::render_mode == e_render_mode_COLOR_GLOW)
					{
						IntType gcol = ResolveHdrLightColor(pext, ObjType(obj_timeline, (IntType)tlObj->part_of));
						render_set_uniform_int(/*"uGlow"*/ STR(2878), IntType(1));
						render_set_uniform_color(/*"uGlowColor"*/ STR(2866), gcol, IntType(1));
						global::shader_uniform_glow = -IntType(1);
					}
				}
			}
		}
	}

	void tl_ext_submit_volume_xforms()
	{
		Shader* sh = GFX ? GFX->shader : nullptr;
		if (!sh)
			return;
		IntType uIdx = sh->GetUniformIndex(StringType("uVolumeXform"));
		if (uIdx >= 0 && g_volumeXformData.Size() >= 256)
		{
			VarType vArr = g_volumeXformData;
			sh->SubmitFloatArray(uIdx, vArr);
		}
		IntType uAmb = sh->GetUniformIndex(StringType("uVolumeAmbient"));
		if (uAmb >= 0 && global::_app)
		{
			IntType sunCol = global::_app->background_sunlight_color_final;
			IntType ambCol = global::_app->background_ambient_color_final;
			RealType ar = std::clamp((double)color_get_red(sunCol) / 255.0 * 0.65 + (double)color_get_red(ambCol) / 255.0 * 0.55, 0.08, 1.15);
			RealType ag = std::clamp((double)color_get_green(sunCol) / 255.0 * 0.65 + (double)color_get_green(ambCol) / 255.0 * 0.55, 0.08, 1.15);
			RealType ab = std::clamp((double)color_get_blue(sunCol) / 255.0 * 0.65 + (double)color_get_blue(ambCol) / 255.0 * 0.55, 0.08, 1.15);
			sh->SubmitVec4(uAmb, ar, ag, ab, 1.0);
		}
	}

	// Pass 1: pack 3D Volume Objects FIRST so they are never crowded out by lights
	IntType tl_ext_pack_volumetric_objects(VarType ldataRef, IntType lcount)
	{
		g_volumeXformData = array_create({ IntType(256), 0.0 });
		withAll (obj_timeline, noone)
		{
			if (lcount >= IntType(16))
				break;
			if (!HasTlExt(self->id))
				continue;
			const TlExtData& ext = GetTlExt(self->id);
			if (ext.volume_mode <= 0 || !self->render_visible || self->hide > 0)
				continue;
			obj_timeline* tlObj = ObjType(obj_timeline, self->id);

			VecType wcenter = point3D_mul_matrix(point3D(0.0, 0.0, 0.0), tlObj->matrix_render);
			VecType vpos = point3D_mul_matrix(wcenter, global::render_gbuf_view_matrix);

			RealType sx = std::max(0.05, (double)tlObj->value_inherit.Value(e_value_SCA_X)) * 8.0;
			RealType sy = std::max(0.05, (double)tlObj->value_inherit.Value(e_value_SCA_Y)) * 8.0;
			RealType sz = std::max(0.05, (double)tlObj->value_inherit.Value(e_value_SCA_Z)) * 8.0;
			RealType rad = std::sqrt(sx * sx + sy * sy + sz * sz);
			IntType col = (IntType)tlObj->value_inherit.Value(e_value_RGB_MUL);

			VecType lookat = point3D_mul_matrix(point3D(0.0, 0.0, 8.0), tlObj->matrix_render);
			VecType vlook = point3D_mul_matrix(lookat, global::render_gbuf_view_matrix);
			VecType vdir = vec3_normalize(point3D_sub(vlook, vpos));

			// Exact view-space -> unit-local ([-1, +1]^3) inverse transform for arbitrary X/Y/Z resize & 3D rotation
			MatrixType s8 = matrix_create(point3D(0, 0, 0), vec3(0, 0, 0), vec3(8.0, 8.0, 8.0));
			MatrixType unitToView = matrix_multiply(matrix_multiply(s8, tlObj->matrix_render), global::render_gbuf_view_matrix);
			MatrixType viewToUnit = matrix_inverse(unitToView);

			RealType shapeCode = 0.0; // 0=Box (CUBE)
			if (tlObj->type == e_tl_type_SPHERE) shapeCode = 1.0;
			else if (tlObj->type == e_tl_type_CYLINDER) shapeCode = 2.0;
			else if (tlObj->type == e_tl_type_CONE) shapeCode = 3.0;

			IntType baseIdx = lcount * IntType(16);
			g_volumeXformData[baseIdx + 0]  = viewToUnit.Real(0);
			g_volumeXformData[baseIdx + 1]  = viewToUnit.Real(4);
			g_volumeXformData[baseIdx + 2]  = viewToUnit.Real(8);
			g_volumeXformData[baseIdx + 3]  = viewToUnit.Real(12);
			g_volumeXformData[baseIdx + 4]  = viewToUnit.Real(1);
			g_volumeXformData[baseIdx + 5]  = viewToUnit.Real(5);
			g_volumeXformData[baseIdx + 6]  = viewToUnit.Real(9);
			g_volumeXformData[baseIdx + 7]  = viewToUnit.Real(13);
			g_volumeXformData[baseIdx + 8]  = viewToUnit.Real(2);
			g_volumeXformData[baseIdx + 9]  = viewToUnit.Real(6);
			g_volumeXformData[baseIdx + 10] = viewToUnit.Real(10);
			g_volumeXformData[baseIdx + 11] = viewToUnit.Real(14);
			g_volumeXformData[baseIdx + 12] = shapeCode;
			g_volumeXformData[baseIdx + 13] = ext.volume_edge_softness;
			g_volumeXformData[baseIdx + 14] = ext.volume_noise_softness;
			g_volumeXformData[baseIdx + 15] = 0.0;

			ldataRef[baseIdx + 0] = vpos.Real(X_);
			ldataRef[baseIdx + 1] = vpos.Real(Y_);
			ldataRef[baseIdx + 2] = vpos.Real(Z_);
			ldataRef[baseIdx + 3] = rad;
			ldataRef[baseIdx + 4] = (RealType)color_get_red(col) / 255.0;
			ldataRef[baseIdx + 5] = (RealType)color_get_green(col) / 255.0;
			ldataRef[baseIdx + 6] = (RealType)color_get_blue(col) / 255.0;
			ldataRef[baseIdx + 7] = ext.volume_density;
			ldataRef[baseIdx + 8] = vdir.Real(X_);
			ldataRef[baseIdx + 9] = vdir.Real(Y_);
			ldataRef[baseIdx + 10] = vdir.Real(Z_);
			ldataRef[baseIdx + 11] = 1.0 + (RealType)ext.volume_mode; // 2.0 = Fog, 3.0 = Cloud, 4.0 = Beam
			ldataRef[baseIdx + 12] = sx;
			ldataRef[baseIdx + 13] = sy;
			ldataRef[baseIdx + 14] = ext.volume_noise_scale;
			ldataRef[baseIdx + 15] = ext.volume_wind_speed;
			lcount++;
		}
		return lcount;
	}

	// Pass 2: pack Emit Lights into uLightData so they also illuminate and scatter INSIDE Volume regions
	IntType tl_ext_pack_volumetric_emit_lights(VarType ldataRef, IntType lcount)
	{
		withAll (obj_timeline, noone)
		{
			if (lcount >= IntType(16))
				break;
			if (!HasTlExt(self->id))
				continue;
			const TlExtData& ext = GetTlExt(self->id);
			if (!ext.hdr_light_enable || !self->render_visible || self->hide > 0)
				continue;
			obj_timeline* tlObj = ObjType(obj_timeline, self->id);
			VecType wcenter = point3D(tlObj->world_pos.Value(X_), tlObj->world_pos.Value(Y_), tlObj->world_pos.Value(Z_));
			QVector<VecType> samplePts;
			CollectHdrLightSamplePoints(tlObj, samplePts);
			VecType hcenter = AverageSamplePoints(samplePts, wcenter);
			VecType hvpos = point3D_mul_matrix(hcenter, global::render_gbuf_view_matrix);
			IntType col = ResolveHdrLightColor(ext, tlObj);

			IntType baseIdx = lcount * IntType(16);
			ldataRef[baseIdx + 0] = hvpos.Real(X_);
			ldataRef[baseIdx + 1] = hvpos.Real(Y_);
			ldataRef[baseIdx + 2] = hvpos.Real(Z_);
			ldataRef[baseIdx + 3] = ext.hdr_light_range;
			ldataRef[baseIdx + 4] = (RealType)color_get_red(col) / 255.0;
			ldataRef[baseIdx + 5] = (RealType)color_get_green(col) / 255.0;
			ldataRef[baseIdx + 6] = (RealType)color_get_blue(col) / 255.0;
			ldataRef[baseIdx + 7] = ext.hdr_light_strength * (1.0 + ext.hdr_light_halo);
			ldataRef[baseIdx + 8] = 0.0;
			ldataRef[baseIdx + 9] = 0.0;
			ldataRef[baseIdx + 10] = 1.0;
			ldataRef[baseIdx + 11] = -1.0; // Point/Emit light source for in-volume scattering
			ldataRef[baseIdx + 12] = 0.0;
			ldataRef[baseIdx + 13] = ext.hdr_light_fade_size;
			ldataRef[baseIdx + 14] = 0.0;
			ldataRef[baseIdx + 15] = 0.0;
			lcount++;
		}
		return lcount;
	}


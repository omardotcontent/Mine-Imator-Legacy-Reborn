	{
		if (!g_extSavedTlKfs.contains(saveId) || !instance_exists(tlId))
			return;
		const QHash<RealType, TlExtData>& kfs = g_extSavedTlKfs[saveId];
		obj_timeline* tlObj = ObjType(obj_timeline, tlId);
		if (!tlObj || !ds_list_valid(tlObj->keyframe_list))
			return;
		for (IntType k = 0; k < ds_list_size(tlObj->keyframe_list); k++)
		{
			IntType kfId = (IntType)DsList(tlObj->keyframe_list).Value(k);
			RealType pos = (RealType)ObjType(obj_keyframe, kfId)->position;
			if (kfs.contains(pos))
				g_kfExtMap[kfId] = kfs[pos];
		}
	}


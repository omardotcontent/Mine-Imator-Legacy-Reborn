	void tl_ext_update_values(ScopeAny self)
	{
		IntType kfCur = sInt(keyframe_current);
		IntType kfNext = sInt(keyframe_next);
		BoolType hasCur = (kfCur != null_ && g_kfExtMap.contains(kfCur));
		BoolType hasNext = (kfNext != null_ && g_kfExtMap.contains(kfNext));
		BoolType hasDef = g_tlExtDefault.contains(self->id);
		if (!hasCur && !hasNext && !hasDef && !g_tlExtMap.contains(self->id))
			return;

		TlExtData fallback = hasDef ? g_tlExtDefault[self->id] : TlExtData();
		auto getKfData = [&](IntType kfId) -> const TlExtData& {
			if (kfId != null_ && g_kfExtMap.contains(kfId))
				return g_kfExtMap[kfId];
			return fallback;
		};

		if (sBool(keyframe_animate))
		{
			const TlExtData& d0 = getKfData(kfCur);
			const TlExtData& d1 = getKfData(kfNext);
			RealType p = (RealType)sVar(keyframe_progress_ease);
			TlExtData out = (p >= 1.0) ? d1 : d0;
			auto lerpf = [p](RealType a, RealType b) -> RealType { return a + (b - a) * p; };

			out.mirror_strength = lerpf(d0.mirror_strength, d1.mirror_strength);
			out.mirror_blur = lerpf(d0.mirror_blur, d1.mirror_blur);
			out.gobo_scale = lerpf(d0.gobo_scale, d1.gobo_scale);
			out.gobo_angle = lerpf(d0.gobo_angle, d1.gobo_angle);
			out.volume_density = lerpf(d0.volume_density, d1.volume_density);
			out.volume_edge_softness = lerpf(d0.volume_edge_softness, d1.volume_edge_softness);
			out.volume_noise_softness = lerpf(d0.volume_noise_softness, d1.volume_noise_softness);
			out.volume_noise_scale = lerpf(d0.volume_noise_scale, d1.volume_noise_scale);
			out.volume_wind_speed = lerpf(d0.volume_wind_speed, d1.volume_wind_speed);
			out.hdr_light_color = merge_color(d0.hdr_light_color, d1.hdr_light_color, p);
			out.hdr_light_strength = lerpf(d0.hdr_light_strength, d1.hdr_light_strength);
			out.hdr_light_range = lerpf(d0.hdr_light_range, d1.hdr_light_range);
			out.hdr_light_fade_size = lerpf(d0.hdr_light_fade_size, d1.hdr_light_fade_size);
			out.hdr_light_halo = lerpf(d0.hdr_light_halo, d1.hdr_light_halo);
			out.mod_shake_pos = lerpf(d0.mod_shake_pos, d1.mod_shake_pos);
			out.mod_shake_rot = lerpf(d0.mod_shake_rot, d1.mod_shake_rot);
			out.mod_shake_speed = lerpf(d0.mod_shake_speed, d1.mod_shake_speed);
			out.mod_wave_amp_z = lerpf(d0.mod_wave_amp_z, d1.mod_wave_amp_z);
			out.mod_wave_rot = lerpf(d0.mod_wave_rot, d1.mod_wave_rot);
			out.mod_wave_speed = lerpf(d0.mod_wave_speed, d1.mod_wave_speed);
			out.mod_spin_speed_z = lerpf(d0.mod_spin_speed_z, d1.mod_spin_speed_z);
			out.mod_spin_speed_x = lerpf(d0.mod_spin_speed_x, d1.mod_spin_speed_x);
			out.mod_bounce_height = lerpf(d0.mod_bounce_height, d1.mod_bounce_height);
			out.mod_bounce_squash = lerpf(d0.mod_bounce_squash, d1.mod_bounce_squash);
			out.mod_bounce_speed = lerpf(d0.mod_bounce_speed, d1.mod_bounce_speed);
			g_tlExtMap[self->id] = out;
		}
		else if (kfCur != null_)
		{
			g_tlExtMap[self->id] = getKfData(kfCur);
		}
		else if (kfNext != null_)
		{
			g_tlExtMap[self->id] = getKfData(kfNext);
		}
		else
		{
			g_tlExtMap[self->id] = fallback;
		}

		if (self->id == global::tl_edit && global::_app && global::_app->frame_editor != null_)
		{
			obj_tab* feTab = ObjType(obj_tab, global::_app->frame_editor);
			if (feTab && feTab->light != null_ && !sArr(value_type).Value(e_value_type_LIGHT))
				ObjType(obj_category, feTab->light)->enabled = g_tlExtMap[self->id].hdr_light_enable;
		}
	}


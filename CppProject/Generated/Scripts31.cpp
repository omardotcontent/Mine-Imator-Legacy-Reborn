	RealType halton(RealType i, RealType xx)
	{
		RealType f, r;
		f = IntType(1);
		r = IntType(0);
		while (i > IntType(0))
		{
			f /= xx;
			r = r + f * (mod(i, xx));
			i = floor((RealType)i / xx);
		}
		
		return r;
	}
	

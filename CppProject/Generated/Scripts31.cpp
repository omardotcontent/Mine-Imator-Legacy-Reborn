	BoolType file_lib_startup()
	{
		log({ /*"working_directory"*/ STR(1325), gmlGlobal::working_directory });
		if (!directory_exists_lib(gmlGlobal::working_directory))
		{
			log({ /*"directory broken"*/ STR(1326) });
			access_error();
			return false;
		}
		IntType surf;
		StringType tmpfile1, tmpfile2;
		surf = surface_create(IntType(32), IntType(32));
		tmpfile1 = file_directory + /*"tmp.png"*/ STR(1327);
		tmpfile2 = data_directory + /*"tmp.png"*/ STR(1327);
		log({ /*"Trying to save files"*/ STR(1328) });
		file_delete_lib(tmpfile1);
		file_delete_lib(tmpfile2);
		surface_save(surf, tmpfile1);
		file_copy_lib(tmpfile1, tmpfile2);
		surface_free(surf);
		if (!file_exists_lib(tmpfile1))
		{
			log({ /*"Couldn't save to file_directory"*/ STR(1329) });
			access_error();
			return false;
		}
		if (!file_exists_lib(tmpfile2))
		{
			log({ /*"Couldn't save to data_directory"*/ STR(1330) });
			access_error();
			return false;
		}
		log({ /*"surface_save OK"*/ STR(1331) });
		IntType tex1, tex2;
		tex1 = texture_create(tmpfile1);
		tex2 = texture_create(tmpfile2);
		if (tex1 < IntType(0) || texture_width(tex1) != IntType(32) || texture_height(tex1) != IntType(32))
		{
			log({ /*"Couldn't load texture from file_directory"*/ STR(1332) });
			access_error();
			return false;
		}
		if (tex2 < IntType(0) || texture_width(tex2) != IntType(32) || texture_height(tex2) != IntType(32))
		{
			log({ /*"Couldn't load texture from data_directory"*/ STR(1333) });
			access_error();
			return false;
		}
		log({ /*"texture_create OK"*/ STR(1334) });
		file_delete_lib(tmpfile1);
		file_delete_lib(tmpfile2);
		if (file_exists_lib(tmpfile1))
		{
			log({ /*"Couldn't delete from file_directory"*/ STR(1335) });
			access_error();
			return false;
		}
		if (file_exists_lib(tmpfile1))
		{
			log({ /*"Couldn't delete from data_directory"*/ STR(1336) });
			access_error();
			return false;
		}
		log({ /*"file_delete_lib OK"*/ STR(1337) });
		return true;
	}
	

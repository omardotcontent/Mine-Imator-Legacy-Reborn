	IntType project_load_start(VarType fn)
	{
		IntType map = json_load({ fn });
		if (!ds_map_valid(map))
		{
			log({ /*"Could not parse JSON file"*/ STR(2715), fn });
			error(/*"errorfilecorrupted"*/ STR(2379));
			return null_;
		}
		if (!is_real(DsMap(map).Value(/*"format"*/ STR(104))))
		{
			log({ /*"Missing parameter \"format\""*/ STR(2716) });
			error(/*"errorfilecorrupted"*/ STR(2379));
			ds_map_destroy(map);
			return null_;
		}
		global::load_format = DsMap(map).Value(/*"format"*/ STR(104));
		if (global::load_format > project_format)
		{
			log({ /*"Too new project, format"*/ STR(2717), global::load_format });
			error(/*"erroropenprojectnewer"*/ STR(2718));
			ds_map_destroy(map);
			return null_;
		}
		else
			if (global::load_format < e_project_FORMAT_110_PRE_1)
			{
				log({ /*"Invalid format"*/ STR(2378), global::load_format });
				error(/*"errorfilecorrupted"*/ STR(2379));
				ds_map_destroy(map);
				return null_;
			}
		
		log({ /*"load_format"*/ STR(1375), global::load_format });
		return map;
	}
	

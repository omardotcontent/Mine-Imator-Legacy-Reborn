	IntType res_load_legacy_block_sheet(StringType fn, VarType format)
	{
		IntType list;
		if (format >= e_project_FORMAT_100_DEMO_2)
			list = global::legacy_block_100_texture_list;
		else
			if (format == e_project_FORMAT_07_DEMO)
				list = global::legacy_block_07_demo_texture_list;
			else
				list = global::legacy_block_05_texture_list;
		
		
		IntType oldtex;
		RealType sheetwid, blocksize;
		oldtex = texture_create(fn);
		sheetwid = IntType(16);
		if (format >= e_project_FORMAT_100_DEMO_2)
			sheetwid = IntType(32);
		blocksize = ceil(texture_width(oldtex) / sheetwid);
		IntType newsurf, newtex;
		newsurf = surface_create((IntType)(global::minecraft_block_sheet_size.Value(IntType(0)) * blocksize), (IntType)(global::minecraft_block_sheet_size.Value(IntType(1)) * blocksize));
		surface_set_target(newsurf);
		draw_clear_alpha(c_black, 0.0);
		gpu_set_blendmode_ext(bm_one, bm_inv_src_alpha);
		draw_texture({ ObjType(obj_resource, global::mc_res)->block_sheet_texture, IntType(0), IntType(0), blocksize / 16.0, blocksize / 16.0 });
		draw_texture_start();
		for (IntType i = IntType(0); i < ds_list_size(list); i++)
		{
			VarType name = DsList(list).Value(i);
			if (name == /*""*/ STR(0))
				continue;
			IntType newindex = ds_list_find_index((IntType)(ObjType(obj_minecraft_assets, global::mc_assets)->block_texture_list), name);
			if (newindex < IntType(0))
			{
				VarType key = ds_map_find_key(global::legacy_block_texture_name_map, name);
				if (is_undefined(key))
				{
					debug({ /*"Could not convert block texture"*/ STR(3188), name });
					continue;
				}
				newindex = ds_list_find_index((IntType)(ObjType(obj_minecraft_assets, global::mc_assets)->block_texture_list), key);
				if (newindex < IntType(0))
				{
					debug({ /*"Could not convert block texture"*/ STR(3188), key });
					continue;
				}
			}
			RealType oldx, oldy, newx, newy;
			oldx = (mod(i, sheetwid)) * blocksize;
			oldy = ((IntType)(i / sheetwid)) * blocksize;
			newx = (mod(newindex, global::minecraft_block_sheet_size.Value(IntType(0)))) * blocksize;
			newy = ((IntType)(newindex / global::minecraft_block_sheet_size.Value(IntType(0)))) * blocksize;
			gpu_set_blendmode(bm_subtract);
			draw_blank(newx, newy, blocksize, blocksize);
			gpu_set_blendmode_ext(bm_one, bm_inv_src_alpha);
			draw_texture_part({ oldtex, newx, newy, oldx, oldy, blocksize, blocksize });
		}
		draw_texture_done();
		gpu_set_blendmode(bm_normal);
		surface_reset_target();
		newtex = texture_surface(newsurf);
		surface_free(newsurf);
		return newtex;
	}
	
	RealType res_update_model_shape(Scope<obj_resource> self)
	{
		if (self->model_shape_alpha_map != null_)
			ds_map_clear(self->model_shape_alpha_map);
		if (self->model_shape_vbuffer_map != null_ && ds_map_size(self->model_shape_vbuffer_map) > IntType(0))
		{
			VarType key = ds_map_find_first(self->model_shape_vbuffer_map);
			while (!is_undefined(key))
			{
				if (instance_exists(key) && idVar(key, vbuffer_default) != DsMap(self->model_shape_vbuffer_map).Value(key))
					vbuffer_destroy(DsMap(self->model_shape_vbuffer_map).Value(key));
				key = ds_map_find_next(self->model_shape_vbuffer_map, key);
			}
			
			ds_map_clear(self->model_shape_vbuffer_map);
		}
		if (self->model_file == null_)
			return IntType(0);
		if (idBool(self->model_file, has_3d_plane))
		{
			if (self->model_shape_alpha_map == null_)
				self->model_shape_alpha_map = ds_map_create();
		}
		if (self->model_shape_vbuffer_map == null_)
			self->model_shape_vbuffer_map = ds_map_create();
		IntType res = self->id;
		if (idInt(res, model_texture_map) == null_)
			res = global::mc_res;
		for (IntType p = IntType(0); p < ds_list_size(idInt(self->model_file, file_part_list)); p++)
		{
			IntType part = DsList(idInt(self->model_file, file_part_list)).Value(p);
			model_part_fill_shape_alpha_map(part, self->model_shape_alpha_map, res, self->model_texture_name_map, self->model_shape_texture_name_map);
			model_part_fill_shape_vbuffer_map(part, self->model_shape_vbuffer_map, self->model_shape_alpha_map, ObjType(obj_model_part, part)->bend_inherit_angle);
		}
		return 0.0;
	}
	

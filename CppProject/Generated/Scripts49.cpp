	void render_high_gbuffer(ScopeAny self)
	{
		VarType gw, gh;
		if (global::render_ssr || global::render_contact_shadows || global::render_outline || global::render_volumetric_lights || global::render_motion_fx || (global::render_effects > 0 && global::render_camera_dof))
		{
			gw = global::render_width;
			gh = global::render_height;
		}
		else
		{
			gw = max({ IntType(1), round(global::render_width * sVar(project_render_ssao_ratio)) });
			gh = max({ IntType(1), round(global::render_height * sVar(project_render_ssao_ratio)) });
		}
		
		global::render_surface_gbuf_depth = surface_require(global::render_surface_gbuf_depth, gw, gh);
		global::render_surface_gbuf_normal = surface_require(global::render_surface_gbuf_normal, gw, gh);
		global::render_surface_gbuf_mat = surface_require(global::render_surface_gbuf_mat, gw, gh);
		surface_set_target_ext(IntType(0), (IntType)(global::render_surface_gbuf_depth));
		surface_set_target_ext(IntType(1), (IntType)(global::render_surface_gbuf_normal));
		surface_set_target_ext(IntType(2), (IntType)(global::render_surface_gbuf_mat));
	{
		gpu_set_blendmode_ext(bm_one, bm_zero);
		draw_clear_alpha(c_white, 0.0);
		render_world_start(global::depth_far);
		global::render_gbuf_proj_matrix = global::proj_matrix;
		global::render_gbuf_view_matrix = global::view_matrix;
		global::render_gbuf_near = global::cam_near;
		global::render_gbuf_far = global::cam_far;
		render_world(self, e_render_mode_HIGH_SSAO_DEPTH_NORMAL);
		render_world_done();
		gpu_set_blendmode(bm_normal);
	}
		surface_reset_target();
	}
	
